const MEETING_COMMON = `[회의] 신사업팀 회의다. 발언은 주장 / 근거(출처 번호) / 질문 형식. 상대 의견의 약점을 하나 이상 짚는다.`;

export function plannerTurn({ round, lastLead }) {
  return {
    extra: `${MEETING_COMMON}
[이번 발언] ${round}라운드, 사업 기획자. ${round > 1 ? '팀장의 반려 이유에 답하거나, 각도를 바꿔(피벗) 다시 제안한다.' : '조사 자료를 보고 사업 아이디어 카드를 낸다.'}
- 카드는 최대 2개. 근거가 없으면 '직감' 라벨. 좋은 게 없으면 "이번 주 제안 없음"과 이유를 쓴다.
- 1,500자 안.
[카드 형식] ### 아이디어: (한 줄 정의) / 고객(나라) / 왜 돈을 내는가 / 데이터 근거 / 수익 구조(단가×건수) / 첫 1만 원을 버는 가장 빠른 방법
${lastLead ? `\n[지난 라운드 팀장 판정 — 결정 사항 / 남은 질문]\n${clip(lastLead, 2500)}` : ''}`,
  };
}

