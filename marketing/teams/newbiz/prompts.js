// 직원 페르소나(marketing/team.js)는 '누구인가', 여기는 '이번에 무엇을 어떤 모양으로 내는가'.
// 지시문은 매 호출마다 AI 에게 보내지므로 짧고 분명하게 유지한다 (토큰 = 비용).

const CLIP = 6000; // 앞 단계 글을 다음 단계로 넘길 때 최대 글자 수

export function clip(text, max = CLIP) {
  const s = String(text || '');
  return s.length > max ? `${s.slice(0, max)}\n…(뒷부분 생략)` : s;
}

