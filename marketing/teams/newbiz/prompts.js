// 글쓰기 사용자 메시지: 앞 단계 자료 + 출처 목록
export function materials(parts) {
  return parts
    .filter((p) => p && p.body)
    .map((p) => `[${p.title}]\n${p.body}`)
    .join('\n\n');
}
